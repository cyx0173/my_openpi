LIBERO_DUMMY_ACTION = [0.0] * 6 + [-1.0]
LIBERO_ENV_RESOLUTION = 256


@dataclasses.dataclass
class Args:
    # Baseline json generated by your baseline collector.
    # Must contain:
    #   task_id, episode_idx, seed, initial_state, chunks[*].executed_actions, chunks[*].noise_seed
    baseline_json: str

    host: str = "0.0.0.0"
    port: int = 8007

    task_suite_name: str = "libero_10"
    resize_size: int = 224
    replan_steps: int = 5
    num_steps_wait: int = -1  # -1 means read from baseline json.

    use_debug_noise: bool = True
    debug_noise_horizon: int = 10
    debug_noise_dim: int = 32

    # "all" or "0,1,2,5,10".
    check_chunks: str = "all"
    max_check_chunks: int = 20  # only used when check_chunks="all"; -1 means all chunks.

    # Tolerances.
    action_tol: float = 1e-5
    obs_state_tol: float = 1e-6
    image_tol: float = 0.0
    sim_state_tol: float = 1e-5

    # Set true only when port points to the same precision server that produced baseline.
    # Example: W4A16 baseline JSON + W4A16 server port 8007.
    compare_recorded_actions: bool = True

    # If true, check next chunk consistency too:
    #   execute recorded A_k on B/C, then infer B_{k+1}/C_{k+1},
    #   compare with recorded A_{k+1}.
    check_next_chunk: bool = True

    output_json: str = ""


class _NumpyEncoder(json.JSONEncoder):
    def default(self, obj: Any):
        if isinstance(obj, np.bool_):
            return bool(obj)
        if isinstance(obj, np.integer):
            return int(obj)
        if isinstance(obj, np.floating):
            return float(obj)
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        return super().default(obj)


def _quat2axisangle(quat):
    quat = np.asarray(quat).copy()

    if quat[3] > 1.0:
        quat[3] = 1.0
    elif quat[3] < -1.0:
        quat[3] = -1.0

    den = np.sqrt(1.0 - quat[3] * quat[3])
    if math.isclose(float(den), 0.0):
        return np.zeros(3)

    return (quat[:3] * 2.0 * math.acos(float(quat[3]))) / den


def _get_obs_element(obs, task_description: str, resize_size: int):
    img_raw = np.ascontiguousarray(obs["agentview_image"][::-1, ::-1])
    wrist_raw = np.ascontiguousarray(obs["robot0_eye_in_hand_image"][::-1, ::-1])

    img = image_tools.convert_to_uint8(
        image_tools.resize_with_pad(img_raw, resize_size, resize_size)
    )
    wrist_img = image_tools.convert_to_uint8(
        image_tools.resize_with_pad(wrist_raw, resize_size, resize_size)
    )

    state = np.concatenate(
        (
            obs["robot0_eef_pos"],
            _quat2axisangle(obs["robot0_eef_quat"]),
            obs["robot0_gripper_qpos"],
        )
    )

    return {
        "observation/image": img,
        "observation/wrist_image": wrist_img,
        "observation/state": state,
        "prompt": str(task_description),
    }


def _get_libero_env(task, resolution: int, seed: int):
    task_description = task.language
    task_bddl_file = (
        pathlib.Path(get_libero_path("bddl_files"))
        / task.problem_folder
        / task.bddl_file
    )
    env_args = {
        "bddl_file_name": task_bddl_file,
        "camera_heights": resolution,
        "camera_widths": resolution,
    }
    env = OffScreenRenderEnv(**env_args)
    env.seed(seed)
    return env, task_description


def _get_current_obs(env):
    # Important: do NOT call env.step here.
    # We need the current observation at the copied state.
    candidates = [
        "_get_observations",
        "_get_observation",
        "_get_obs",
    ]

    for name in candidates:
        fn = getattr(env, name, None)
        if callable(fn):
            return fn()

    inner = getattr(env, "env", None)
    if inner is not None:
        for name in candidates:
            fn = getattr(inner, name, None)
            if callable(fn):
                return fn()

    raise RuntimeError(
        "Cannot get current observation without stepping. "
        "Please inspect OffScreenRenderEnv methods and patch _get_current_obs()."
    )


def _capture_env_state(env):
    data = env.sim.data
    state = {
        "sim_state_flat": env.sim.get_state().flatten().copy(),
        "ctrl": data.ctrl.copy(),
        "mocap_pos": data.mocap_pos.copy(),
        "mocap_quat": data.mocap_quat.copy(),
    }

    # These buffers may matter for exact deterministic MuJoCo stepping.
    optional_fields = [
        "qacc_warmstart",
        "qfrc_applied",
        "xfrc_applied",
    ]
    for name in optional_fields:
        if hasattr(data, name):
            state[name] = getattr(data, name).copy()

    return state


def _restore_env_state(env, state):
    env.sim.set_state_from_flattened(np.asarray(state["sim_state_flat"]))

    data = env.sim.data

    def _copy_if_present(key, attr):
        if key not in state or not hasattr(data, attr):
            return
        dst = getattr(data, attr)
        src = np.asarray(state[key])
        if dst.shape == src.shape:
            dst[:] = src

    _copy_if_present("ctrl", "ctrl")
    _copy_if_present("mocap_pos", "mocap_pos")
    _copy_if_present("mocap_quat", "mocap_quat")
    _copy_if_present("qacc_warmstart", "qacc_warmstart")
    _copy_if_present("qfrc_applied", "qfrc_applied")
    _copy_if_present("xfrc_applied", "xfrc_applied")

    env.sim.forward()

    # Refresh robosuite observables if available.
    for obj in [env, getattr(env, "env", None)]:
        if obj is None:
            continue
        fn = getattr(obj, "_update_observables", None)
        if callable(fn):
            try:
                fn(force=True)
            except TypeError:
                fn()


def _array_diff(a, b):
    a = np.asarray(a)
    b = np.asarray(b)

    if a.shape != b.shape:
        return {
            "same_shape": False,
            "shape_a": list(a.shape),
            "shape_b": list(b.shape),
            "max_abs": None,
            "mean_abs": None,
        }

    d = np.abs(a.astype(np.float64) - b.astype(np.float64))
    return {
        "same_shape": True,
        "shape_a": list(a.shape),
        "shape_b": list(b.shape),
        "max_abs": float(d.max()) if d.size else 0.0,
        "mean_abs": float(d.mean()) if d.size else 0.0,
    }


def _ok_by_tol(diff, tol: float):
    return (
        bool(diff.get("same_shape", False))
        and diff.get("max_abs") is not None
        and float(diff["max_abs"]) <= float(tol)
    )


def _obs_diff(obs_a, obs_b):
    keys = [
        "robot0_eef_pos",
        "robot0_eef_quat",
        "robot0_gripper_qpos",
        "agentview_image",
        "robot0_eye_in_hand_image",
    ]
    out = {}
    for k in keys:
        if k in obs_a and k in obs_b:
            out[k] = _array_diff(obs_a[k], obs_b[k])
    return out


def _element_diff(elem_a, elem_b):
    keys = [
        "observation/image",
        "observation/wrist_image",
        "observation/state",
    ]
    out = {}
    for k in keys:
        if k in elem_a and k in elem_b:
            out[k] = _array_diff(elem_a[k], elem_b[k])
    return out


def _policy_input_ok(elem_metrics, args: Args):
    state_ok = True
    image_ok = True

    if "observation/state" in elem_metrics:
        state_ok = _ok_by_tol(elem_metrics["observation/state"], args.obs_state_tol)

    for key in ["observation/image", "observation/wrist_image"]:
        if key in elem_metrics:
            image_ok = image_ok and _ok_by_tol(elem_metrics[key], args.image_tol)

    return bool(state_ok and image_ok)


def _make_debug_noise(noise_seed: int, horizon: int, dim: int):
    rng = np.random.default_rng(int(noise_seed))
    return rng.standard_normal(size=(int(horizon), int(dim))).astype(np.float32)


def _add_debug_noise(element: dict, args: Args, noise_seed):
    if not args.use_debug_noise:
        return dict(element), {
            "enabled": False,
            "seed": None,
            "shape": None,
        }

    if noise_seed is None:
        raise ValueError("use_debug_noise=True but baseline chunk has no noise_seed")

    debug_noise = _make_debug_noise(
        int(noise_seed),
        int(args.debug_noise_horizon),
        int(args.debug_noise_dim),
    )

    out = dict(element)
    out["debug_noise"] = debug_noise.copy()

    return out, {
        "enabled": True,
        "seed": int(noise_seed),
        "shape": list(debug_noise.shape),
    }


def _to_action_array(actions, replan_steps: int):
    return np.asarray(actions[:replan_steps], dtype=np.float64)


def _resolve_check_chunks(args: Args, num_chunks: int):
    s = args.check_chunks.strip().lower()

    if s == "all":
        if args.max_check_chunks is not None and int(args.max_check_chunks) >= 0:
            return set(range(min(num_chunks, int(args.max_check_chunks))))
        return set(range(num_chunks))

    out = set()
    for x in args.check_chunks.split(","):
        x = x.strip()
        if not x:
            continue
        k = int(x)
        if 0 <= k < num_chunks:
            out.add(k)
    return out


def _prepare_env_at_initial(env, initial_state, num_steps_wait: int):
    env.reset()
    obs = env.set_init_state(initial_state)
    done = False
    for _ in range(int(num_steps_wait)):
        obs, _, done, _ = env.step(LIBERO_DUMMY_ACTION)
    return obs, done


def _infer_action(client, obs, task_description, args: Args, noise_seed):
    elem = _get_obs_element(obs, task_description, args.resize_size)
    elem, noise_meta = _add_debug_noise(elem, args, noise_seed)
    out = client.infer(elem)
    act = _to_action_array(out["actions"], args.replan_steps)
    return act, elem, noise_meta, out


def _compare_three_actions(name: str, a_recorded, b_replay, c_copy, args: Args):
    diff_ab = _array_diff(a_recorded, b_replay)
    diff_ac = _array_diff(a_recorded, c_copy)
    diff_bc = _array_diff(b_replay, c_copy)

    ok_ab = _ok_by_tol(diff_ab, args.action_tol)
    ok_ac = _ok_by_tol(diff_ac, args.action_tol)
    ok_bc = _ok_by_tol(diff_bc, args.action_tol)

    logging.info(
        f"[{name} A-vs-B recorded-vs-replay] "
        f"max_abs={diff_ab['max_abs']} mean_abs={diff_ab['mean_abs']} ok={ok_ab}"
    )
    logging.info(
        f"[{name} A-vs-C recorded-vs-copy]   "
        f"max_abs={diff_ac['max_abs']} mean_abs={diff_ac['mean_abs']} ok={ok_ac}"
    )
    logging.info(
        f"[{name} B-vs-C replay-vs-copy]     "
        f"max_abs={diff_bc['max_abs']} mean_abs={diff_bc['mean_abs']} ok={ok_bc}"
    )

    return {
        "recorded_vs_replay": diff_ab,
        "recorded_vs_copy": diff_ac,
        "replay_vs_copy": diff_bc,
        "recorded_vs_replay_ok": bool(ok_ab),
        "recorded_vs_copy_ok": bool(ok_ac),
        "replay_vs_copy_ok": bool(ok_bc),
        "all_ok": bool(ok_ab and ok_ac and ok_bc),
    }


def main(args: Args) -> None:
    baseline_path = pathlib.Path(args.baseline_json)
    with open(baseline_path, "r", encoding="utf-8") as f:
        record = json.load(f)

    task_id = int(record["task_id"])
    episode_idx = int(record.get("episode_idx", 0))
    seed = int(record.get("seed", 7))
    task_description_recorded = record.get("task_description", "")

    num_steps_wait = (
        int(record.get("num_steps_wait", 10))
        if int(args.num_steps_wait) < 0
        else int(args.num_steps_wait)
    )

    chunks = record["chunks"]
    if not chunks:
        raise ValueError(f"No chunks found in baseline json: {baseline_path}")

    if "initial_state" not in record:
        raise ValueError(
            "baseline json does not contain initial_state. "
            "Please collect baseline with initial_state saved."
        )
    initial_state = np.asarray(record["initial_state"], dtype=np.float64)

    benchmark_dict = benchmark.get_benchmark_dict()
    task_suite = benchmark_dict[args.task_suite_name]()
    task = task_suite.get_task(task_id)

    prefix_env = None
    copy_env = None

    results = {
        "baseline_json": str(baseline_path),
        "task_suite_name": args.task_suite_name,
        "task_id": task_id,
        "task_description_recorded": task_description_recorded,
        "episode_idx": episode_idx,
        "seed": seed,
        "num_steps_wait": num_steps_wait,
        "server": {
            "host": args.host,
            "port": int(args.port),
        },
        "compare_recorded_actions": bool(args.compare_recorded_actions),
        "check_next_chunk": bool(args.check_next_chunk),
        "check_chunks": [],
        "overall": {
            "current_recorded_vs_replay_all_ok": True,
            "current_recorded_vs_copy_all_ok": True,
            "current_replay_vs_copy_all_ok": True,
            "next_recorded_vs_replay_all_ok": True,
            "next_recorded_vs_copy_all_ok": True,
            "next_replay_vs_copy_all_ok": True,
            "dynamics_replay_vs_copy_all_ok": True,
            "policy_input_copy_all_ok": True,
        },
    }

    try:
        prefix_env, task_description = _get_libero_env(task, LIBERO_ENV_RESOLUTION, seed)
        copy_env, _ = _get_libero_env(task, LIBERO_ENV_RESOLUTION, seed)

        client = _websocket_client_policy.WebsocketClientPolicy(args.host, args.port)

        logging.info(f"Baseline: {baseline_path}")
        logging.info(f"Task {task_id}: {task_description}")
        logging.info(f"Recorded task desc: {task_description_recorded}")
        logging.info(f"Server: ws://{args.host}:{args.port}")
        logging.info(f"Episode idx: {episode_idx}, seed: {seed}")
        logging.info(f"num_steps_wait={num_steps_wait}, chunks={len(chunks)}")

        obs_prefix, done_prefix = _prepare_env_at_initial(
            prefix_env,
            initial_state,
            num_steps_wait,
        )
        _prepare_env_at_initial(
            copy_env,
            initial_state,
            num_steps_wait,
        )

        selected_chunks = _resolve_check_chunks(args, len(chunks))
        logging.info(f"Selected check chunks: {sorted(selected_chunks)}")

        for k, chunk in enumerate(chunks):
            recorded_current = _to_action_array(
                chunk["executed_actions"],
                args.replan_steps,
            )

            if k not in selected_chunks:
                # Just advance prefix_env along recorded baseline actions.
                for action in recorded_current:
                    obs_prefix, _, done_prefix, _ = prefix_env.step(action)

                if done_prefix:
                    logging.info(f"[STOP] prefix_env reached done at non-check chunk={k}")
                    break
                continue

            logging.info("=" * 100)
            logging.info(f"[CHECK] chunk={k} step_start={chunk.get('step_start')}")

            # ------------------------------------------------------------------
            # Current chunk check:
            #   A_k = recorded baseline actions
            #   B_k = replay prefix_env inference
            #   C_k = copied copy_env inference
            # ------------------------------------------------------------------
            state_snapshot = _capture_env_state(prefix_env)
            _restore_env_state(copy_env, state_snapshot)

            obs_b = _get_current_obs(prefix_env)
            obs_c = _get_current_obs(copy_env)

            obs_copy_diff = _obs_diff(obs_b, obs_c)

            elem_b_raw = _get_obs_element(obs_b, task_description, args.resize_size)
            elem_c_raw = _get_obs_element(obs_c, task_description, args.resize_size)
            elem_copy_diff = _element_diff(elem_b_raw, elem_c_raw)
            policy_input_copy_ok = _policy_input_ok(elem_copy_diff, args)

            noise_seed_current = chunk.get("noise_seed", None)

            act_b_current, elem_b_current, noise_b, out_b = _infer_action(
                client, obs_b, task_description, args, noise_seed_current
            )
            act_c_current, elem_c_current, noise_c, out_c = _infer_action(
                client, obs_c, task_description, args, noise_seed_current
            )

            current_action_compare = _compare_three_actions(
                "CURRENT",
                recorded_current,
                act_b_current,
                act_c_current,
                args,
            )

            logging.info(
                f"[POLICY-INPUT-COPY] ok={policy_input_copy_ok} "
                f"state_max_abs={elem_copy_diff.get('observation/state', {}).get('max_abs')} "
                f"image_max_abs={elem_copy_diff.get('observation/image', {}).get('max_abs')} "
                f"wrist_max_abs={elem_copy_diff.get('observation/wrist_image', {}).get('max_abs')}"
            )

            # ------------------------------------------------------------------
            # Execute recorded A_k on B/C and compare dynamics.
            # This also advances prefix_env to chunk k+1 for the main loop.
            # ------------------------------------------------------------------
            done_b_after = False
            done_c_after = False
            obs_b_after = None
            obs_c_after = None

            for action in recorded_current:
                obs_b_after, _, done_b_after, _ = prefix_env.step(action)
                obs_c_after, _, done_c_after, _ = copy_env.step(action)

            sim_state_b_after = prefix_env.sim.get_state().flatten()
            sim_state_c_after = copy_env.sim.get_state().flatten()
            dynamics_state_diff = _array_diff(sim_state_b_after, sim_state_c_after)
            dynamics_ok = (
                _ok_by_tol(dynamics_state_diff, args.sim_state_tol)
                and bool(done_b_after) == bool(done_c_after)
            )

            after_obs_diff = {}
            if obs_b_after is not None and obs_c_after is not None:
                after_obs_diff = _obs_diff(obs_b_after, obs_c_after)

            logging.info(
                f"[DYNAMICS B-vs-C after recorded A_k] "
                f"sim_state_max_abs={dynamics_state_diff['max_abs']} "
                f"sim_state_mean_abs={dynamics_state_diff['mean_abs']} "
                f"done_b={done_b_after} done_c={done_c_after} ok={dynamics_ok}"
            )

            # ------------------------------------------------------------------
            # Next chunk check:
            #   infer from B/C after executing recorded A_k.
            #   Compare with recorded A_{k+1}.
            # ------------------------------------------------------------------
            next_action_compare = None
            next_policy_input_copy_ok = None
            next_elem_copy_diff = None

            has_next = (k + 1) < len(chunks)
            if args.check_next_chunk and has_next and not done_b_after and not done_c_after:
                next_chunk = chunks[k + 1]
                recorded_next = _to_action_array(
                    next_chunk["executed_actions"],
                    args.replan_steps,
                )
                noise_seed_next = next_chunk.get("noise_seed", None)

                # Use current obs returned by env.step after recorded current chunk.
                obs_b_next = obs_b_after
                obs_c_next = obs_c_after

                elem_b_next_raw = _get_obs_element(
                    obs_b_next, task_description, args.resize_size
                )
                elem_c_next_raw = _get_obs_element(
                    obs_c_next, task_description, args.resize_size
                )
                next_elem_copy_diff = _element_diff(elem_b_next_raw, elem_c_next_raw)
                next_policy_input_copy_ok = _policy_input_ok(next_elem_copy_diff, args)

                act_b_next, _, noise_b_next, _ = _infer_action(
                    client, obs_b_next, task_description, args, noise_seed_next
                )
                act_c_next, _, noise_c_next, _ = _infer_action(
                    client, obs_c_next, task_description, args, noise_seed_next
                )

                next_action_compare = _compare_three_actions(
                    "NEXT",
                    recorded_next,
                    act_b_next,
                    act_c_next,
                    args,
                )

                logging.info(
                    f"[NEXT POLICY-INPUT-COPY] ok={next_policy_input_copy_ok} "
                    f"state_max_abs={next_elem_copy_diff.get('observation/state', {}).get('max_abs')} "
                    f"image_max_abs={next_elem_copy_diff.get('observation/image', {}).get('max_abs')} "
                    f"wrist_max_abs={next_elem_copy_diff.get('observation/wrist_image', {}).get('max_abs')}"
                )

            # ------------------------------------------------------------------
            # Save per-chunk check record.
            # ------------------------------------------------------------------
            check_record = {
                "chunk_idx": int(k),
                "step_start": int(chunk.get("step_start", -1)),
                "noise_seed_current": noise_b["seed"],
                "obs_copy_diff_before_current": obs_copy_diff,
                "policy_input_copy_diff_before_current": elem_copy_diff,
                "policy_input_copy_ok_before_current": bool(policy_input_copy_ok),
                "current_action_compare": current_action_compare,
                "dynamics_after_recorded_current": {
                    "sim_state_diff": dynamics_state_diff,
                    "done_replay": bool(done_b_after),
                    "done_copy": bool(done_c_after),
                    "ok": bool(dynamics_ok),
                    "after_obs_diff": after_obs_diff,
                },
                "next_action_compare": next_action_compare,
                "next_policy_input_copy_ok": (
                    bool(next_policy_input_copy_ok)
                    if next_policy_input_copy_ok is not None
                    else None
                ),
                "next_policy_input_copy_diff": next_elem_copy_diff,
            }
            results["check_chunks"].append(check_record)

            # Update overall flags.
            cur = current_action_compare
            if not cur["recorded_vs_replay_ok"]:
                results["overall"]["current_recorded_vs_replay_all_ok"] = False
            if not cur["recorded_vs_copy_ok"]:
                results["overall"]["current_recorded_vs_copy_all_ok"] = False
            if not cur["replay_vs_copy_ok"]:
                results["overall"]["current_replay_vs_copy_all_ok"] = False
            if not policy_input_copy_ok:
                results["overall"]["policy_input_copy_all_ok"] = False
            if not dynamics_ok:
                results["overall"]["dynamics_replay_vs_copy_all_ok"] = False

            if next_action_compare is not None:
                nxt = next_action_compare
                if not nxt["recorded_vs_replay_ok"]:
                    results["overall"]["next_recorded_vs_replay_all_ok"] = False
                if not nxt["recorded_vs_copy_ok"]:
                    results["overall"]["next_recorded_vs_copy_all_ok"] = False
                if not nxt["replay_vs_copy_ok"]:
                    results["overall"]["next_replay_vs_copy_all_ok"] = False
                if next_policy_input_copy_ok is False:
                    results["overall"]["policy_input_copy_all_ok"] = False

            obs_prefix = obs_b_after
            done_prefix = done_b_after

            if done_prefix:
                logging.info(f"[STOP] prefix_env reached done at checked chunk={k}")
                break

        if not results["check_chunks"]:
            logging.warning("No chunks checked. Please adjust --args.check-chunks.")

        logging.info("=" * 100)
        logging.info(f"Overall: {results['overall']}")

    finally:
        if prefix_env is not None:
            prefix_env.close()
        if copy_env is not None:
            copy_env.close()

    output_path = (
        pathlib.Path(args.output_json)
        if args.output_json
        else baseline_path.with_name(
            baseline_path.stem + f"_abc_state_copy_check_port{args.port}.json"
        )
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2, cls=_NumpyEncoder, ensure_ascii=False)

    logging.info(f"[Saved] {output_path}")


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    tyro.cli(main)
